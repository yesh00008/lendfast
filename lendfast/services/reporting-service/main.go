// ─── Response Models ─────────────────────────────────────────────────────────

type PortfolioReport struct {
	GeneratedAt      string            `json:"generated_at"`
	TotalLoans       int               `json:"total_loans"`
	ActiveLoans      int               `json:"active_loans"`
	TotalDisbursed   float64           `json:"total_disbursed"`
	TotalOutstanding float64           `json:"total_outstanding"`
	AverageRate      float64           `json:"average_interest_rate"`
	ByStatus         []StatusBreakdown `json:"by_status"`
	ByLoanType       []TypeBreakdown   `json:"by_loan_type"`
	MonthlyTrend     []MonthlyMetric   `json:"monthly_trend"`
}

type StatusBreakdown struct {
	Status string  `json:"status"`
	Count  int     `json:"count"`
	Amount float64 `json:"amount"`
}

type TypeBreakdown struct {
	LoanType string  `json:"loan_type"`
	Count    int     `json:"count"`
	Amount   float64 `json:"amount"`
	AvgRate  float64 `json:"avg_rate"`
}

type MonthlyMetric struct {
	Month       string  `json:"month"`
	Disbursed   float64 `json:"disbursed"`
	Collections float64 `json:"collections"`
	NewLoans    int     `json:"new_loans"`
}

type DelinquencyReport struct {
	GeneratedAt      string            `json:"generated_at"`
	TotalDelinquent  int               `json:"total_delinquent"`
	TotalOverdue     float64           `json:"total_overdue"`
	DelinquencyRate  float64           `json:"delinquency_rate_pct"`
	ByLevel          []LevelBreakdown  `json:"by_escalation_level"`
	ByAgingBucket    []AgingBucket     `json:"by_aging_bucket"`
	TopDelinquencies []DelinquencyItem `json:"top_delinquencies"`
}

type LevelBreakdown struct {
	Level  string  `json:"level"`
	Count  int     `json:"count"`
	Amount float64 `json:"amount"`
}

type AgingBucket struct {
	Bucket string  `json:"bucket"`
	Count  int     `json:"count"`
	Amount float64 `json:"amount"`
}

type DelinquencyItem struct {
	DelinquencyID string  `json:"delinquency_id"`
	LoanID        string  `json:"loan_id"`
	BorrowerID    string  `json:"borrower_id"`
	DaysPastDue   int     `json:"days_past_due"`
	AmountOverdue float64 `json:"amount_overdue"`
	Level         string  `json:"escalation_level"`
}

type RevenueReport struct {
	GeneratedAt     string          `json:"generated_at"`
	Period          string          `json:"period"`
	TotalRevenue    float64         `json:"total_revenue"`
	InterestIncome  float64         `json:"interest_income"`
	FeeIncome       float64         `json:"fee_income"`
	PrincipalRepaid float64         `json:"principal_repaid"`
	MonthlyRevenue  []MonthRevenue  `json:"monthly_revenue"`
	ByPaymentMethod []MethodRevenue `json:"by_payment_method"`
}

type MonthRevenue struct {
	Month           string  `json:"month"`
	InterestIncome  float64 `json:"interest_income"`
	FeeIncome       float64 `json:"fee_income"`
	PrincipalRepaid float64 `json:"principal_repaid"`
	TotalPayments   int     `json:"total_payments"`
}

type MethodRevenue struct {
	Method string  `json:"method"`
	Count  int     `json:"count"`
	Amount float64 `json:"amount"`
}

type DashboardReport struct {
	GeneratedAt         string     `json:"generated_at"`
	Overview            Overview   `json:"overview"`
	ApplicationPipeline Pipeline   `json:"application_pipeline"`
	RecentActivity      []Activity `json:"recent_activity"`
	Alerts              []Alert    `json:"alerts"`
}

type Overview struct {
	TotalBorrowers    int     `json:"total_borrowers"`
	ActiveBorrowers   int     `json:"active_borrowers"`
	TotalApplications int     `json:"total_applications"`
	PendingApps       int     `json:"pending_applications"`
	ActiveLoans       int     `json:"active_loans"`
	TotalOutstanding  float64 `json:"total_outstanding"`
	DelinquencyRate   float64 `json:"delinquency_rate_pct"`
	AvgCreditScore    float64 `json:"avg_credit_score"`
}

type Pipeline struct {
	Draft       int `json:"draft"`
	Submitted   int `json:"submitted"`
	UnderReview int `json:"under_review"`
	Approved    int `json:"approved"`
	Rejected    int `json:"rejected"`
	Disbursed   int `json:"disbursed"`
}

type Activity struct {
	Type      string `json:"type"`
	Detail    string `json:"detail"`
	Timestamp string `json:"timestamp"`
}

type Alert struct {
	Severity string `json:"severity"`
	Message  string `json:"message"`
}


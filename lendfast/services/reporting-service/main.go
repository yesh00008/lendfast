func generateAlerts(delinquent, pendingApps int) []Alert {
	alerts := []Alert{}

	if delinquent > 10 {
		alerts = append(alerts, Alert{
			Severity: "critical",
			Message:  fmt.Sprintf("High delinquency count: %d open delinquencies", delinquent),
		})
	} else if delinquent > 5 {
		alerts = append(alerts, Alert{
			Severity: "warning",
			Message:  fmt.Sprintf("Elevated delinquency count: %d open delinquencies", delinquent),
		})
	}

	if pendingApps > 20 {
		alerts = append(alerts, Alert{
			Severity: "warning",
			Message:  fmt.Sprintf("Application backlog: %d applications pending review", pendingApps),
		})
	}

	// Check for legal-level delinquencies
	var legalCount int
	if db != nil {
		db.QueryRow(`SELECT COUNT(*) FROM delinquencies WHERE escalation_level = 'legal' AND status = 'open'`).Scan(&legalCount)
	}
	if legalCount > 0 {
		alerts = append(alerts, Alert{
			Severity: "critical",
			Message:  fmt.Sprintf("%d delinquencies at legal escalation level", legalCount),
		})
	}

	if len(alerts) == 0 {
		alerts = append(alerts, Alert{
			Severity: "info",
			Message:  "All metrics within normal ranges",
		})
	}

	return alerts
}

func cacheReport(key string, data interface{}) {
	if redisClient == nil {
		return
	}
	bytes, err := json.Marshal(data)
	if err == nil {
		redisClient.Set(ctx, key, bytes, 5*time.Minute)
	}
}


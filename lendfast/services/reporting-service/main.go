func portfolioReport(c *gin.Context) {
	start := time.Now()
	cacheKey := "report:portfolio"

	// Check Redis cache
	if cached, err := redisClient.Get(ctx, cacheKey).Result(); err == nil {
		c.Data(http.StatusOK, "application/json", []byte(cached))
		return
	}

	report := PortfolioReport{
		GeneratedAt: time.Now().Format(time.RFC3339),
	}

	// Total counts and amounts
	db.QueryRow(`SELECT COUNT(*), COALESCE(SUM(principal_amount), 0), COALESCE(AVG(interest_rate), 0) FROM loans`).Scan(
		&report.TotalLoans, &report.TotalDisbursed, &report.AverageRate)

	db.QueryRow(`SELECT COUNT(*), COALESCE(SUM(remaining_balance), 0) FROM loans WHERE status = 'active'`).Scan(
		&report.ActiveLoans, &report.TotalOutstanding)

	// By status
	rows, err := db.Query(`
		SELECT status, COUNT(*), COALESCE(SUM(principal_amount), 0)
		FROM loans GROUP BY status ORDER BY COUNT(*) DESC`)
	if err == nil {
		defer rows.Close()
		for rows.Next() {
			var sb StatusBreakdown
			rows.Scan(&sb.Status, &sb.Count, &sb.Amount)
			report.ByStatus = append(report.ByStatus, sb)
		}
	}

	// By loan type
	rows2, err := db.Query(`
		SELECT loan_type, COUNT(*), COALESCE(SUM(principal_amount), 0), COALESCE(AVG(interest_rate), 0)
		FROM loans GROUP BY loan_type ORDER BY SUM(principal_amount) DESC`)
	if err == nil {
		defer rows2.Close()
		for rows2.Next() {
			var tb TypeBreakdown
			rows2.Scan(&tb.LoanType, &tb.Count, &tb.Amount, &tb.AvgRate)
			report.ByLoanType = append(report.ByLoanType, tb)
		}
	}

	// Monthly trend (last 12 months)
	rows3, err := db.Query(`
		SELECT TO_CHAR(created_at, 'YYYY-MM') AS month,
			COALESCE(SUM(principal_amount), 0) AS disbursed,
			COUNT(*) AS new_loans
		FROM loans
		WHERE created_at >= NOW() - INTERVAL '12 months'
		GROUP BY TO_CHAR(created_at, 'YYYY-MM')
		ORDER BY month`)
	if err == nil {
		defer rows3.Close()
		for rows3.Next() {
			var mm MonthlyMetric
			var newLoans int
			rows3.Scan(&mm.Month, &mm.Disbursed, &newLoans)
			mm.NewLoans = newLoans
			report.MonthlyTrend = append(report.MonthlyTrend, mm)
		}
	}

	// Cache for 5 minutes
	cacheReport(cacheKey, report)

	reportsGenerated.WithLabelValues("portfolio").Inc()
	reportLatency.WithLabelValues("portfolio").Observe(time.Since(start).Seconds())

	c.JSON(http.StatusOK, gin.H{"status": "success", "data": report})
}

func delinquencyReport(c *gin.Context) {
	start := time.Now()
	cacheKey := "report:delinquency"

	if cached, err := redisClient.Get(ctx, cacheKey).Result(); err == nil {
		c.Data(http.StatusOK, "application/json", []byte(cached))
		return
	}

	report := DelinquencyReport{
		GeneratedAt: time.Now().Format(time.RFC3339),
	}

	// Total delinquent
	db.QueryRow(`SELECT COUNT(*), COALESCE(SUM(amount_overdue), 0) FROM delinquencies WHERE status = 'open'`).Scan(
		&report.TotalDelinquent, &report.TotalOverdue)

	// Delinquency rate
	var activeLoans int
	db.QueryRow(`SELECT COUNT(*) FROM loans WHERE status = 'active'`).Scan(&activeLoans)
	if activeLoans > 0 {
		report.DelinquencyRate = float64(report.TotalDelinquent) / float64(activeLoans) * 100
	}

	// By escalation level
	rows, err := db.Query(`
		SELECT escalation_level, COUNT(*), COALESCE(SUM(amount_overdue), 0)
		FROM delinquencies WHERE status = 'open'
		GROUP BY escalation_level
		ORDER BY CASE escalation_level WHEN 'legal' THEN 4 WHEN 'collections' THEN 3 WHEN 'warning' THEN 2 ELSE 1 END DESC`)
	if err == nil {
		defer rows.Close()
		for rows.Next() {
			var lb LevelBreakdown
			rows.Scan(&lb.Level, &lb.Count, &lb.Amount)
			report.ByLevel = append(report.ByLevel, lb)
		}
	}

	// By aging bucket
	agingQuery := `
		SELECT
			CASE
				WHEN days_past_due <= 30 THEN '1-30 days'
				WHEN days_past_due <= 60 THEN '31-60 days'
				WHEN days_past_due <= 90 THEN '61-90 days'
				ELSE '90+ days'
			END AS bucket,
			COUNT(*), COALESCE(SUM(amount_overdue), 0)
		FROM delinquencies WHERE status = 'open'
		GROUP BY bucket
		ORDER BY MIN(days_past_due)`
	rows2, err := db.Query(agingQuery)
	if err == nil {
		defer rows2.Close()
		for rows2.Next() {
			var ab AgingBucket
			rows2.Scan(&ab.Bucket, &ab.Count, &ab.Amount)
			report.ByAgingBucket = append(report.ByAgingBucket, ab)
		}
	}

	// Top 10 delinquencies
	rows3, err := db.Query(`
		SELECT delinquency_id, loan_id, borrower_id, days_past_due, amount_overdue, escalation_level
		FROM delinquencies WHERE status = 'open'
		ORDER BY amount_overdue DESC LIMIT 10`)
	if err == nil {
		defer rows3.Close()
		for rows3.Next() {
			var di DelinquencyItem
			rows3.Scan(&di.DelinquencyID, &di.LoanID, &di.BorrowerID, &di.DaysPastDue, &di.AmountOverdue, &di.Level)
			report.TopDelinquencies = append(report.TopDelinquencies, di)
		}
	}

	cacheReport(cacheKey, report)
	reportsGenerated.WithLabelValues("delinquency").Inc()
	reportLatency.WithLabelValues("delinquency").Observe(time.Since(start).Seconds())

	c.JSON(http.StatusOK, gin.H{"status": "success", "data": report})
}

func revenueReport(c *gin.Context) {
	start := time.Now()
	period := c.DefaultQuery("period", "12")
	cacheKey := fmt.Sprintf("report:revenue:%s", period)

	if cached, err := redisClient.Get(ctx, cacheKey).Result(); err == nil {
		c.Data(http.StatusOK, "application/json", []byte(cached))
		return
	}

	report := RevenueReport{
		GeneratedAt: time.Now().Format(time.RFC3339),
		Period:      period + " months",
	}

	// Total revenue from payments
	db.QueryRow(`
		SELECT COALESCE(SUM(interest_portion), 0), COALESCE(SUM(late_fee), 0), COALESCE(SUM(principal_portion), 0)
		FROM payments WHERE status = 'completed' AND created_at >= NOW() - ($1 || ' months')::INTERVAL`, period,
	).Scan(&report.InterestIncome, &report.FeeIncome, &report.PrincipalRepaid)
	report.TotalRevenue = report.InterestIncome + report.FeeIncome

	// Monthly revenue
	rows, err := db.Query(`
		SELECT TO_CHAR(created_at, 'YYYY-MM') AS month,
			COALESCE(SUM(interest_portion), 0) AS interest,
			COALESCE(SUM(late_fee), 0) AS fees,
			COALESCE(SUM(principal_portion), 0) AS principal,
			COUNT(*) AS payment_count
		FROM payments
		WHERE status = 'completed' AND created_at >= NOW() - ($1 || ' months')::INTERVAL
		GROUP BY TO_CHAR(created_at, 'YYYY-MM')
		ORDER BY month`, period)
	if err == nil {
		defer rows.Close()
		for rows.Next() {
			var mr MonthRevenue
			rows.Scan(&mr.Month, &mr.InterestIncome, &mr.FeeIncome, &mr.PrincipalRepaid, &mr.TotalPayments)
			report.MonthlyRevenue = append(report.MonthlyRevenue, mr)
		}
	}

	// By payment method
	rows2, err := db.Query(`
		SELECT payment_method, COUNT(*), COALESCE(SUM(amount), 0)
		FROM payments
		WHERE status = 'completed' AND created_at >= NOW() - ($1 || ' months')::INTERVAL
		GROUP BY payment_method ORDER BY SUM(amount) DESC`, period)
	if err == nil {
		defer rows2.Close()
		for rows2.Next() {
			var mr MethodRevenue
			rows2.Scan(&mr.Method, &mr.Count, &mr.Amount)
			report.ByPaymentMethod = append(report.ByPaymentMethod, mr)
		}
	}

	cacheReport(cacheKey, report)
	reportsGenerated.WithLabelValues("revenue").Inc()
	reportLatency.WithLabelValues("revenue").Observe(time.Since(start).Seconds())

	c.JSON(http.StatusOK, gin.H{"status": "success", "data": report})
}

func dashboardReport(c *gin.Context) {
	start := time.Now()
	cacheKey := "report:dashboard"

	if cached, err := redisClient.Get(ctx, cacheKey).Result(); err == nil {
		c.Data(http.StatusOK, "application/json", []byte(cached))
		return
	}

	report := DashboardReport{
		GeneratedAt: time.Now().Format(time.RFC3339),
	}

	// Overview
	db.QueryRow(`SELECT COUNT(*) FROM borrowers`).Scan(&report.Overview.TotalBorrowers)
	db.QueryRow(`SELECT COUNT(*) FROM borrowers WHERE status = 'active'`).Scan(&report.Overview.ActiveBorrowers)
	db.QueryRow(`SELECT COUNT(*) FROM applications`).Scan(&report.Overview.TotalApplications)
	db.QueryRow(`SELECT COUNT(*) FROM applications WHERE status IN ('submitted', 'under_review')`).Scan(&report.Overview.PendingApps)
	db.QueryRow(`SELECT COUNT(*), COALESCE(SUM(remaining_balance), 0) FROM loans WHERE status = 'active'`).Scan(
		&report.Overview.ActiveLoans, &report.Overview.TotalOutstanding)
	db.QueryRow(`SELECT COALESCE(AVG(credit_score), 0) FROM borrowers WHERE credit_score > 0`).Scan(&report.Overview.AvgCreditScore)

	// Delinquency rate
	var delinquent int
	db.QueryRow(`SELECT COUNT(*) FROM delinquencies WHERE status = 'open'`).Scan(&delinquent)
	if report.Overview.ActiveLoans > 0 {
		report.Overview.DelinquencyRate = float64(delinquent) / float64(report.Overview.ActiveLoans) * 100
	}

	// Application pipeline
	db.QueryRow(`SELECT COUNT(*) FROM applications WHERE status = 'draft'`).Scan(&report.ApplicationPipeline.Draft)
	db.QueryRow(`SELECT COUNT(*) FROM applications WHERE status = 'submitted'`).Scan(&report.ApplicationPipeline.Submitted)
	db.QueryRow(`SELECT COUNT(*) FROM applications WHERE status = 'under_review'`).Scan(&report.ApplicationPipeline.UnderReview)
	db.QueryRow(`SELECT COUNT(*) FROM applications WHERE status = 'approved'`).Scan(&report.ApplicationPipeline.Approved)
	db.QueryRow(`SELECT COUNT(*) FROM applications WHERE status = 'rejected'`).Scan(&report.ApplicationPipeline.Rejected)
	db.QueryRow(`SELECT COUNT(*) FROM applications WHERE status = 'disbursed'`).Scan(&report.ApplicationPipeline.Disbursed)

	// Recent activity (last 10 items)
	rows, err := db.Query(`
		(SELECT 'loan_created' AS type, CONCAT('New loan ', loan_id, ' - $', principal_amount) AS detail, created_at
		 FROM loans ORDER BY created_at DESC LIMIT 3)
		UNION ALL
		(SELECT 'payment' AS type, CONCAT('Payment of $', amount, ' on ', loan_id) AS detail, created_at
		 FROM payments WHERE status = 'completed' ORDER BY created_at DESC LIMIT 3)
		UNION ALL
		(SELECT 'application' AS type, CONCAT('Application ', application_id, ' - ', status) AS detail, created_at
		 FROM applications ORDER BY created_at DESC LIMIT 4)
		ORDER BY created_at DESC LIMIT 10`)
	if err == nil {
		defer rows.Close()
		for rows.Next() {
			var a Activity
			var ts time.Time
			rows.Scan(&a.Type, &a.Detail, &ts)
			a.Timestamp = ts.Format(time.RFC3339)
			report.RecentActivity = append(report.RecentActivity, a)
		}
	}

	// Alerts
	report.Alerts = generateAlerts(delinquent, report.Overview.PendingApps)

	cacheReport(cacheKey, report)
	reportsGenerated.WithLabelValues("dashboard").Inc()
	reportLatency.WithLabelValues("dashboard").Observe(time.Since(start).Seconds())

	c.JSON(http.StatusOK, gin.H{"status": "success", "data": report})
}

func borrowerReport(c *gin.Context) {
	borrowerID := c.Param("borrower_id")

	type BorrowerDetail struct {
		BorrowerID       string  `json:"borrower_id"`
		Name             string  `json:"name"`
		Email            string  `json:"email"`
		CreditScore      int     `json:"credit_score"`
		Status           string  `json:"status"`
		TotalLoans       int     `json:"total_loans"`
		ActiveLoans      int     `json:"active_loans"`
		TotalBorrowed    float64 `json:"total_borrowed"`
		TotalOutstanding float64 `json:"total_outstanding"`
		TotalPaid        float64 `json:"total_paid"`
		Delinquencies    int     `json:"open_delinquencies"`
		OnTimeRate       float64 `json:"on_time_payment_rate_pct"`
	}

	var report BorrowerDetail
	report.BorrowerID = borrowerID

	// Borrower info
	err := db.QueryRow(`
		SELECT CONCAT(first_name, ' ', last_name), email, credit_score, status 
		FROM borrowers WHERE borrower_id = $1`, borrowerID,
	).Scan(&report.Name, &report.Email, &report.CreditScore, &report.Status)
	if err == sql.ErrNoRows {
		c.JSON(http.StatusNotFound, gin.H{"error": "Borrower not found"})
		return
	}

	// Loan stats
	db.QueryRow(`SELECT COUNT(*), COALESCE(SUM(principal_amount), 0) FROM loans WHERE borrower_id = $1`, borrowerID).Scan(
		&report.TotalLoans, &report.TotalBorrowed)
	db.QueryRow(`SELECT COUNT(*), COALESCE(SUM(remaining_balance), 0) FROM loans WHERE borrower_id = $1 AND status = 'active'`, borrowerID).Scan(
		&report.ActiveLoans, &report.TotalOutstanding)

	// Payment stats
	db.QueryRow(`SELECT COALESCE(SUM(amount), 0) FROM payments WHERE loan_id IN (SELECT loan_id FROM loans WHERE borrower_id = $1) AND status = 'completed'`, borrowerID).Scan(
		&report.TotalPaid)

	// Delinquencies
	db.QueryRow(`SELECT COUNT(*) FROM delinquencies WHERE borrower_id = $1 AND status = 'open'`, borrowerID).Scan(&report.Delinquencies)

	// On-time rate
	var totalInstallments, paidOnTime int
	db.QueryRow(`SELECT COUNT(*) FROM repayment_schedule WHERE loan_id IN (SELECT loan_id FROM loans WHERE borrower_id = $1)`, borrowerID).Scan(&totalInstallments)
	db.QueryRow(`SELECT COUNT(*) FROM repayment_schedule WHERE loan_id IN (SELECT loan_id FROM loans WHERE borrower_id = $1) AND status = 'paid' AND paid_date <= due_date`, borrowerID).Scan(&paidOnTime)
	if totalInstallments > 0 {
		report.OnTimeRate = float64(paidOnTime) / float64(totalInstallments) * 100
	}

	reportsGenerated.WithLabelValues("borrower").Inc()

	c.JSON(http.StatusOK, gin.H{"status": "success", "data": report})
}

